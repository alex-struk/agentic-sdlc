function criterionCard(c, domain, model) {
  const cov = domain.coverage;
  const tested = cov.covered.includes(c.id);
  const notTestable = cov.notTestable.includes(c.id);
  const reason = notTestable ? (model.notTestable.find((x) => x?.id === c.id)?.reason ?? "") : "";
  const classes = ["criterion"];
  if (c.state === "obsolete") classes.push("is-obsolete");
  else if (notTestable) classes.push("is-not-testable");
  const filterState = c.state === "obsolete" ? "obsolete" : tested ? "tested" : notTestable ? "not-testable" : "untested";

  const rows = [];
  if (c.given) rows.push(["given", e(c.given)]);
  if (c.when) rows.push(["when", e(c.when)]);
  if (c.then) rows.push(["then", e(c.then)]);
  if (tested) rows.push(["test", `<code>tests/acceptance/${e(domain.name)}/${e(c.id)}.spec.ts</code>`]);
  else if (notTestable) rows.push(["not testable", e(reason)]);
  for (const t of model.targets) {
    const row = resultRows(model.latest.get(t)).find((r) => r?.id === c.id);
    if (row) rows.push([`against ${t}`, `${chip(row.result, row.result)}${row.ruled ? ` ruled ${e(row.ruled)}` : ""}`]);
  }
  const cites = c.cites ?? [];
  if (cites.length) {
    rows.push(["cites", cites.map((cite) => `<code>${e(cite.line !== undefined ? `${cite.path}:${cite.line}` : cite.path)}</code>`).join("<br>")]);
  }
  if (c.reconciliation) rows.push(["reconciliation", e(c.reconciliation)]);
  if (c.replaces) rows.push(["replaces", e(c.replaces)]);
  if (c.supersededBy) rows.push(["superseded by", e(c.supersededBy)]);
  for (const note of c.notes ?? []) rows.push(["note", inline(note)]);

  return `<article class="${classes.join(" ")}" data-state="${e(filterState)}">
  <header>
    <span class="id">${e(c.id)}</span>
    ${chip(c.state ?? "", c.state === "obsolete" ? "muted" : "open")}
    ${chip(`${c.confidence ?? ""}`, c.confidence === "open" ? "escalated" : "muted")}
    <span class="chip muted">v${e(String(c.version ?? 1))}</span>
  </header>
  <p class="statement">${e(c.statement ?? "")}</p>
  ${rows.length ? `<dl>${rows.map(([k, v]) => `<dt>${e(k)}</dt><dd>${v}</dd>`).join("")}</dl>` : ""}
</article>`;
}

const FILTER_SCRIPT = `<script>
(function () {
  var bar = document.querySelector(".filters");
  if (!bar) return;
  bar.hidden = false;
  var cards = Array.prototype.slice.call(document.querySelectorAll(".criterion"));
  bar.addEventListener("click", function (event) {
    var button = event.target.closest("button[data-filter]");
    if (!button) return;
    var want = button.getAttribute("data-filter");
    Array.prototype.forEach.call(bar.querySelectorAll("button"), function (b) {
      b.setAttribute("aria-pressed", String(b === button));
    });
    cards.forEach(function (card) {
      card.hidden = want !== "all" && card.getAttribute("data-state") !== want;
    });
  });
})();
</script>`;

function domainPage(domain, model) {
  const counts = {
    all: domain.criteria.length,
    tested: domain.coverage.covered.length,
    "not-testable": domain.coverage.notTestable.length,
    untested: domain.coverage.missing.length,
    obsolete: domain.criteria.filter((c) => c.state === "obsolete").length,
  };
  const labels = { all: "All", tested: "Has a test", "not-testable": "Not testable", untested: "No test yet", obsolete: "Obsolete" };
  // The filter bar is written hidden and revealed by the script, so a reader without
  // JavaScript is never shown controls that would do nothing.
  const filters = `<div class="filters" hidden>${Object.keys(labels).map((k) =>
    `<button type="button" data-filter="${e(k)}" aria-pressed="${k === "all"}">${e(labels[k])} (${e(String(counts[k]))})</button>`).join("")}</div>`;

  return [
    `<div class="page-head"><h1>${e(domain.name)}</h1>`,
    `<p class="lede">${e(String(domain.total))} criteria, ${e(String(counts.tested))} with a derived acceptance test, ${e(String(counts["not-testable"]))} recorded as not testable through the contract surface.</p></div>`,
    filters,
    domain.criteria.map((c) => criterionCard(c, domain, model)).join("\n"),
    FILTER_SCRIPT,
  ].join("\n");
}

// A legend, not a lecture, and only for the terms this project's own log actually uses.
// A project whose gates are all held by people should not have persona agents explained
// to it, and one whose policy sets no re-read quota should not be told what sampling is.
function gateLegend(model) {
  const items = [];
  if (model.gates.some((g) => g.held_by === "agent")) {
    items.push(["Made by", "A persona agent is an agent that read the gate holder's written brief and ruled in that role. A person is someone who ran the command themselves."]);
  }
  if (model.sampled.size > 0) {
    items.push(["Human re-read", "Policy sets a number of agent-held rulings per gate per week for a person to read back. Those are marked here. It is a spot check on the agents, not a second approval."]);
  }
  if (model.gates.some((g) => g.verdict === "escalated")) {
    items.push(["Escalated", "The holder declined to rule and passed the decision up, which the policy requires for high-risk changes."]);
  }
  if (items.length === 0) return "";
  return `<section><h2>What the columns mean</h2><dl class="legend">${items.map(([k, v]) =>
    `<dt>${e(k)}</dt><dd>${e(v)}</dd>`).join("")}</dl></section>`;
}

